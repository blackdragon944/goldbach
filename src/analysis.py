# ========================================================== 5. self-similarity

def section_selfsim():
    """Good pair (p, q) of n (a = 3).  Shift n -> n + 2^k.
       'q-shift': (p, q + 2^k) good for n + 2^k ?   'p-shift': (p + 2^k, q) good ?
    For 2^k > n the submask condition is automatic, only primality matters."""
    Nn = 1 << 12
    K = 26
    LIM = Nn + (1 << K) + 8
    isp = np.frombuffer(g.sieve(LIM), dtype=np.uint8).astype(bool)
    pairs = []
    for n in range(10, Nn, 2):
        m = n - 3
        for p in submasks_odd(m):
            p = int(p)
            if isp[p] and isp[n - p]:
                pairs.append((n, p))
    P = np.array(pairs, dtype=np.int64)
    n0, p0 = P[:, 0], P[:, 1]
    q0 = n0 - p0
    out = []
    for k in range(1, K + 1):
        t = 1 << k
        n1 = n0 + t
        sub_q = ((p0 & (n1 - 3)) == p0)
        sub_p = (((p0 + t) & (n1 - 3)) == (p0 + t)) & ((p0 + t) < n1 - 3)
        good_q = sub_q & isp[q0 + t] & isp[p0]
        good_p = sub_p & isp[p0 + t] & isp[q0]
        # baseline: probability that a random odd number near q0 + 2^k is prime
        mid = np.median(q0 + t)
        base = 2 / math.log(mid)
        out.append([k, len(P), f"{sub_q.mean():.4f}", f"{good_q.mean():.4f}", f"{sub_p.mean():.4f}",
                    f"{good_p.mean():.4f}", f"{base:.4f}", f"{good_q.mean() / base:.3f}"])
    with open(os.path.join(DATA, "self_similarity.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["k", "pairs", "frac_submask_kept_qshift", "frac_good_qshift", "frac_submask_kept_pshift",
                    "frac_good_pshift", "2/ln(q+2^k)", "ratio_good_qshift_to_baseline"])
        w.writerows(out)
    big = [r for r in out if (1 << r[0]) > Nn]
    num("selfsimPairs", fmt_int(len(P)))
    num("selfsimRatioMin", f"{min(float(r[7]) for r in big):.2f}")
    num("selfsimRatioMax", f"{max(float(r[7]) for r in big):.2f}")
    small = [r for r in out if r[0] <= 4]
    num("selfsimKeptKOne", f"{100 * float(out[0][2]):.1f}")
    num("selfsimKeptKFour", f"{100 * float(out[3][2]):.1f}")
    num("selfsimNn", fmt_int(Nn))
    print("[selfsim]", out[:4], "...", out[-2:])

    fig, ax = plt.subplots(figsize=(5.2, 2.8))
    ks = [r[0] for r in out]
    ax.semilogy(ks, [float(r[3]) for r in out], "o-", ms=3, lw=0.8, color=ACC, label="$(p,q+2^k)$ good for $n+2^k$")
    ax.semilogy(ks, [float(r[5]) for r in out], "s-", ms=3, lw=0.8, color=ACC2, label="$(p+2^k,q)$ good for $n+2^k$")
    ax.semilogy(ks, [float(r[6]) for r in out], ":", color=MUTED, label="$2/\\ln(q+2^k)$")
    ax.axvline(math.log2(Nn), color=MUTED, lw=0.5)
    ax.set_xlabel("$k$")
    ax.set_ylabel("fraction of good pairs kept")
    ax.legend(frameon=False, fontsize=7)
    savefig(fig, "self_similarity")


