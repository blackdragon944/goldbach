def popcount(x):
    return np.bitwise_count(np.asarray(x, dtype=np.uint64)).astype(np.int64)


def parse_scan(text: str):
    recs, hist, exc, info = [], {}, [], {}
    for line in text.splitlines():
        if line.startswith("record "):
            _, n, a = line.split()
            recs.append((int(n), int(a)))
        elif line.startswith("exceptions"):
            exc = [int(x) for x in line.split(":", 1)[1].split()]
        elif line.startswith("hist n<="):
            head, rest = line.split(":", 1)
            hist[int(head[8:])] = {int(k): int(v) for k, v in (t.split(":") for t in rest.split())}
        elif line.startswith("# scan"):
            info["scan_seconds"] = float(line.split(":")[1].split()[0])
    return recs, hist, exc, info


