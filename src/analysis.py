SPARSE = None
SPARSE_ONES = 3   # "sparse" = at most three binary ones, as in the shape of the records n = w + d


def sparse_numbers(limit_bits=64):
    """All positive integers below 2^limit_bits with at most SPARSE_ONES binary ones, sorted."""
    global SPARSE
    if SPARSE is None:
        from itertools import combinations
        s = set()
        for k in range(1, SPARSE_ONES + 1):
            for bits in combinations(range(limit_bits), k):
                s.add(sum(1 << b for b in bits))
        SPARSE = np.array(sorted(s), dtype=np.uint64)
    return SPARSE


def sparse_below(n: int) -> int:
    S = sparse_numbers()
    i = np.searchsorted(S, np.uint64(n), side="right") - 1
    return int(S[i])


