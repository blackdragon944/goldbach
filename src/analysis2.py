def next_odd_prime(d: int) -> int:
    x = d + 1
    while True:
        if x >= 3 and x % 2 and all(x % r for r in range(3, math.isqrt(x) + 1, 2)):
            return x
        x += 1


def record_shape(n: int, a: int):
    """Write n = w + d with popcount(w) <= 3, 0 < d < 2^{nu_2(w)} and a = least odd prime > d
    (the shape of the records, Section 5).  Returns (LaTeX string, holds?)."""
    for j in range(1, n.bit_length()):
        d = n % (1 << j)
        w = n - d
        if d > 0 and w > 0 and bin(w).count("1") <= 3 and next_odd_prime(d) == a:
            bits = [i for i in reversed(range(w.bit_length())) if (w >> i) & 1]
            return "$" + "+".join(f"2^{{{i}}}" for i in bits) + f"+{d}$", True
    return "--", False


