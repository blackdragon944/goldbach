# ================================================== items 1-2: G_3 in [2^19, 2^20)

def section_block():
    G = np.fromfile(os.path.join(DATA, "G3_upto_2e20.bin"), dtype=np.uint32).astype(np.int64)
    n = np.arange(G.size, dtype=np.int64) * 2
    blk = (n >= 1 << 19) & (n < 1 << 20)
    assert blk.sum() == 1 << 18
    s = popcount(n - 3)
    rows, out = [], []
    for k in range(1, 21):
        m = blk & (s == k)
        if not m.any():
            continue
        cnt = int(m.sum())
        # control: n = 2^19 + 2j, n - 3 = 2^19 + 2(j-2) + 1 for j >= 2  =>  s = 2 + s(j - 2);
        # j - 2 runs over [0, 2^18 - 3], plus n = 2^19 (s = 18) and n = 2^19 + 2 (s = 19)
        expect = comb(18, k - 2) if k >= 2 else 0
        expect += (k == 18) - (k == 19) + (k == 19) - (k == 20)
        assert cnt == expect, (k, cnt, expect)
        cand = 2 ** (k - 1) - 2 if k >= 2 else 0
        rows.append([k, fmt_int(cnt), fmt_int(cand), f"{G[m].mean():.1f}", fmt_int(int(G[m].min())),
                     f"{100 * (G[m] == 0).mean():.2f}"])
        out.append([k, cnt, cand, f"{G[m].mean():.3f}", int(G[m].min()), f"{(G[m] == 0).mean():.6f}"])
    write_rows("table_G3_popcount", rows)
    with open(os.path.join(DATA, "G3_by_popcount_block_2e19_2e20.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["popcount_n_minus_3", "count", "candidates", "mean_G3", "min_G3", "frac_zero"])
        w.writerows(out)
    num("blockCount", fmt_int(int(blk.sum())))
    num("blockSmin", int(s[blk].min()))
    num("blockSmax", int(s[blk].max()))
    num("blockZeroTotal", fmt_int(int((G[blk] == 0).sum())))
    # largest s with a zero
    zs = [k for k in range(1, 21) if (blk & (s == k) & (G == 0)).any()]
    num("blockMaxSZero", max(zs))
    num("blockMinGAtSixteen", fmt_int(int(G[blk & (s == 16)].min())))
    # old (wrong) version: n <= 10^6 only
    old = blk & (n <= 10**6)
    num("blockOldCount", fmt_int(int(old.sum())))
    num("blockOldNine", fmt_int(int((old & (s == 9)).sum())))
    num("blockOldSixteen", fmt_int(int((old & (s == 16)).sum())))

    # ---- item 2: divisibility factor at fixed s
    c3 = n % 3 == 0
    c5 = (n % 5 == 0) & ~c3
    c0 = ~c3 & (n % 5 != 0)
    r3, r5, drows = [], [], []
    for k in range(2, 21):
        m = blk & (s == k)
        sizes = [int((m & c).sum()) for c in (c3, c5, c0)]
        if min(sizes) < 300:          # ratios of means only where every class has >= 300 n
            continue
        g3, g5, g0 = (G[m & c].mean() for c in (c3, c5, c0))
        r3.append(g3 / g0)
        r5.append(g5 / g0)
        drows.append([k] + sizes + [f"{g3 / g0:.3f}", f"{g5 / g0:.3f}"])
    ks = [r[0] for r in drows]
    num("divSlo", min(ks))
    num("divShi", max(ks))
    num("divThreeMin", f"{min(r3):.2f}")
    num("divThreeMax", f"{max(r3):.2f}")
    num("divFiveMin", f"{min(r5):.2f}")
    num("divFiveMax", f"{max(r5):.2f}")
    # restricted to s >= 9 (G_3 large, zeros negligible)
    big = [i for i, k in enumerate(ks) if k >= 9]
    num("divThreeMinBig", f"{min(r3[i] for i in big):.2f}")
    num("divThreeMaxBig", f"{max(r3[i] for i in big):.2f}")
    num("divFiveMinBig", f"{min(r5[i] for i in big):.2f}")
    num("divFiveMaxBig", f"{max(r5[i] for i in big):.2f}")
    for nm, c in (("Three", c3), ("Five", c5), ("Other", c0)):
        num(f"divZero{nm}", pct((G[blk & c] == 0).mean()))
        num(f"divCount{nm}", fmt_int(int((blk & c).sum())))
    with open(os.path.join(DATA, "G3_divisibility_block.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["popcount_n_minus_3", "n_div3", "n_div5_not3", "n_other", "meanG3_div3_over_other",
                    "meanG3_div5_over_other"])
        w.writerows(drows)
    print(f"[block] ratios 3|n {min(r3):.2f}..{max(r3):.2f}, 5|n {min(r5):.2f}..{max(r5):.2f} for s in {ks}")


