def parse_ext(path):
    d = {"upto": {}, "histC": {}, "akdef": {}, "crec": [], "cfail_first": {}}
    for line in open(path):
        t = line.split()
        if not t:
            continue
        if t[0] == "upto":
            N = int(t[1])
            kv = dict(zip(t[2::2], t[3::2]))
            i = t.index("cfail")
            d["upto"][N] = {k: int(v) for k, v in kv.items() if k not in ("cfail",) and v.isdigit()}
            d["upto"][N]["cfail"] = [int(x) for x in t[i + 1:i + 5]]
        elif t[0] == "histC":
            N = int(t[1][3:-1])
            d["histC"][N] = {int(a): int(c) for a, c in (x.split(":") for x in t[2:])}
        elif t[0] == "akdeficit":
            N = int(t[1][3:-1])
            d["akdef"][N] = {int(a): int(c) for a, c in (x.split(":") for x in t[2:])}
        elif t[0] == "crecord":
            d["crec"].append((int(t[1]), int(t[2])))
        elif t[0] == "cfail_first":
            d["cfail_first"][float(t[1][2:-1])] = sorted(int(x) for x in t[2:])
        elif t[0] == "lemma_violations":
            d["lemma_bad"] = int(t[1])
        elif t[0] == "abin_max":
            d["abin_max"] = (int(t[1]), int(t[3]))
        elif t[0] == "abin_exceptions_list":
            d["abin_exc"] = [int(x) for x in t[1:]]
        elif t[0] == "chen_hard3_upto_1e6":
            d["chen_list"] = [int(x) for x in t[2:]]
        elif line.startswith("# ext scan"):
            d["seconds"] = float(line.split(":")[1].split()[0])
    return d


